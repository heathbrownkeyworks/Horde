// Builds view/icons.js from Lucide (interface icons) and Horde's
// Game-icons.net artwork in assets/icons (vitals, skills, equipment).
// Usage: node tools/view/build-icons.mjs <lucide-svelte package directory>
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const lucideDir = process.argv[2];
if (!lucideDir) {
    console.error('usage: node tools/view/build-icons.mjs <lucide-svelte package directory>');
    process.exit(2);
}

const lucideNames = [
    'arrow-left', 'bell', 'bell-off', 'check', 'chevron-right', 'circle-alert', 'circle-check', 'corner-down-left',
    'crosshair', 'door-open', 'flame', 'footprints', 'gamepad-2', 'hourglass', 'house', 'house-plus', 'info',
    'keyboard', 'list-filter', 'loader-circle', 'locate-fixed', 'magnet', 'map-pin', 'paw-print', 'settings-2', 'shield-check',
    'shield-off', 'skull', 'sparkles', 'star', 'swords', 'tent', 'trash-2', 'triangle-alert', 'undo-2', 'user-x',
    'users', 'wand-sparkles', 'x', 'zap'
];

const lucidePackage = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8'));
const lucide = {};
for (const name of lucideNames) {
    const source = readFileSync(join(lucideDir, 'dist', 'icons', name + '.svelte'), 'utf8');
    const match = source.match(/const iconNode = (\[.*?\]);\n/s);
    if (!match) throw new Error('no iconNode in ' + name);
    lucide[name] = JSON.parse(match[1]);
}

const game = {};
const iconsDir = join(root, 'assets', 'icons');
for (const file of readdirSync(iconsDir).filter(f => f.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(iconsDir, file), 'utf8');
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
    if (!paths.length || !/viewBox="0 0 512 512"/.test(svg)) throw new Error('unexpected artwork in ' + file);
    game[file.slice(0, -4)] = paths;
}

const output = `// Generated by tools/view/build-icons.mjs. Do not edit.
//
// Lucide ${lucidePackage.version} (https://lucide.dev) icons: ISC License,
// Copyright (c) Lucide Icons and Contributors. Icons derived from Feather are
// MIT licensed, Copyright (c) 2013-present Cole Bemis. Full texts: licenses/Lucide-ISC.txt.
//
// Game-icons.net artwork (https://game-icons.net) is licensed under CC BY 3.0.
// Authors and sources: licenses/Game-Icons-Attribution.md.
window.HordeIcons = ${JSON.stringify({ lucide, game })};
`;
writeFileSync(join(root, 'view', 'icons.js'), output);
console.log(`view/icons.js: ${Object.keys(lucide).length} Lucide, ${Object.keys(game).length} Game-icons`);
